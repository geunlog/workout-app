const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const bytes = new Map();
const legacyKey = 'geunlog-body-v1';
const updatedAt = '2026-11-18T01:00:00.000Z';
const record = {id:'morning',at:'2026-11-18T08:00',weight:80,note:'합성 메모',createdAt:updatedAt,updatedAt};
const legacy = JSON.stringify({version:1,records:[record],baseline:'morning'});
bytes.set(legacyKey, legacy);
const localStorage = { getItem:key=>bytes.get(key)??null, setItem:(key,value)=>bytes.set(key,value) };
const ctx = {window:{},localStorage,structuredClone};
const source = fs.readFileSync('app.js','utf8').split('// ==== 원본 script')[0];
vm.runInNewContext(source,ctx);
const tracker=ctx.window.BodyTracker;
const day='2026-11-18';
const backup=JSON.parse(JSON.stringify(tracker.read()));
backup.previousDayMeals[day]={status:'cleared',kcalAbs:null,updatedAt};
backup.overlay.previousDayMeals=structuredClone(backup.previousDayMeals);
tracker.validate(backup);
function restore(input){localStorage.setItem(tracker.key,JSON.stringify(tracker.merge(input)));}
restore(backup);
restore(JSON.parse(legacy));
const older=structuredClone(backup);
older.previousDayMeals[day]={status:'over',kcalAbs:150,updatedAt:'2026-11-17T12:00:00Z'};
older.overlay.previousDayMeals=older.previousDayMeals;
restore(older);
assert.equal(tracker.read().previousDayMeals[day].status,'cleared');
assert.equal(tracker.read().records[0].note,record.note);
assert.equal(bytes.get(legacyKey),legacy);
const saved=bytes.get(tracker.key);
older.previousDayMeals[day].kcalAbs=-1;
assert.throws(()=>restore(older));
assert.equal(bytes.get(tracker.key),saved);
console.log('PASS v2 validation, v1/v2 merge, meal tombstone, note, malformed import and immutable legacy bytes');
